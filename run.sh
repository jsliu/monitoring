#!/usr/bin/env bash
# Monitoring: Prometheus + Grafana + Telegram alerts for ../intraday and ../thetagang (docker-compose.yml).
# Needs Docker Desktop and .env (copy .env.example). Places no orders.
#
#   ./run.sh up          # start (or update) the stack; Grafana at http://localhost:3000 (user admin)
#   ./run.sh status      # containers + which projects' metrics Prometheus can reach
#   ./run.sh test-alert  # send a Telegram test message with .env's bot token and chat id
#   ./run.sh fit         # size the thetagang tables to their rows (no scrollbars)
#   ./run.sh down        # stop it (history is kept in the Docker volumes)
#   ./run.sh render      # only (re)write Grafana's Telegram contact point from .env
#
# Grafana 11.3 turns an env-substituted numeric chat id into a number and then rejects it, so the contact point is
# rendered from .env into a git-ignored file (mode 600) with the values quoted, before Grafana starts.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"  # repo root
ENV_FILE="${MONITORING_ENV_FILE:-.env}"
CONTACT_POINT="${CONTACT_POINT_FILE:-grafana/provisioning/alerting/contact-point.yaml}"
COMPOSE=(docker compose -f docker-compose.yml --env-file "$ENV_FILE")

env_value() {  # the literal text after KEY= in .env (last one wins) -- never evaluated as shell code
    local line
    line=$(grep -E "^$1=" "$ENV_FILE" | tail -n 1 || true)
    printf '%s' "${line#*=}"
}

need_env() {
    if [[ ! -f "$ENV_FILE" ]]; then
        echo "error: $ENV_FILE is missing -- copy .env.example to it and fill it in" >&2
        exit 1
    fi
}

render_contact_point() {
    local TELEGRAM_BOT_TOKEN TELEGRAM_CHAT_ID GF_SECURITY_ADMIN_PASSWORD
    TELEGRAM_BOT_TOKEN=$(env_value TELEGRAM_BOT_TOKEN)
    TELEGRAM_CHAT_ID=$(env_value TELEGRAM_CHAT_ID)
    GF_SECURITY_ADMIN_PASSWORD=$(env_value GF_SECURITY_ADMIN_PASSWORD)
    if [[ ! "${TELEGRAM_BOT_TOKEN:-}" =~ ^[0-9]+:[A-Za-z0-9_-]+$ ]]; then
        echo "error: TELEGRAM_BOT_TOKEN in $ENV_FILE is not a bot token (<digits>:<letters>) -- see .env.example" >&2
        exit 1
    fi
    if [[ ! "${TELEGRAM_CHAT_ID:-}" =~ ^-?[0-9]+$ ]]; then
        echo "error: TELEGRAM_CHAT_ID in $ENV_FILE is not a numeric chat id -- see .env.example" >&2
        exit 1
    fi
    if [[ -z "${GF_SECURITY_ADMIN_PASSWORD:-}" ]]; then
        echo "error: set GF_SECURITY_ADMIN_PASSWORD in $ENV_FILE (the Grafana admin login)" >&2
        exit 1
    fi
    local tmp="$CONTACT_POINT.tmp"
    trap 'rm -f "$CONTACT_POINT.tmp"' EXIT  # an interrupted render must not leave the token behind
    (umask 077 && cat > "$tmp" <<YAML
# Generated by run.sh from .env -- git-ignored, do not edit or commit.
apiVersion: 1
contactPoints:
  - orgId: 1
    name: telegram
    receivers:
      - uid: telegram
        type: telegram
        disableResolveMessage: false
        settings:
          bottoken: '${TELEGRAM_BOT_TOKEN}'
          chatid: '${TELEGRAM_CHAT_ID}'
YAML
)
    if cmp -s "$tmp" "$CONTACT_POINT"; then rm -f "$tmp"; return 1; fi  # unchanged
    mv "$tmp" "$CONTACT_POINT"
    return 0
}

case "${1:-}" in
    up)
        need_env
        changed=0
        render_contact_point && changed=1
        "${COMPOSE[@]}" up -d
        if [[ $changed == 1 ]]; then
            "${COMPOSE[@]}" restart grafana >/dev/null  # Grafana reads provisioning only at startup
        fi
        echo "Grafana: http://localhost:3000 (user admin)  Prometheus: http://localhost:9090"
        ;;
    render)
        need_env
        render_contact_point || true
        echo "wrote $CONTACT_POINT"
        ;;
    down)
        need_env
        "${COMPOSE[@]}" down
        ;;
    status)
        need_env
        "${COMPOSE[@]}" ps
        curl -fsS http://127.0.0.1:9090/api/v1/targets 2>/dev/null | python3 -c 'import json, sys
for t in json.load(sys.stdin)["data"]["activeTargets"]:
    print("  %-10s %-5s %s" % (t["labels"]["job"], t["health"], t["scrapeUrl"]))' \
            || echo "prometheus: not reachable (is the stack up?)"
        ;;
    fit)
        python3 fit_tables.py  # size the thetagang tables to their rows; Grafana reloads the file
        ;;
    test-alert)
        need_env
        TELEGRAM_BOT_TOKEN=$(env_value TELEGRAM_BOT_TOKEN)
        TELEGRAM_CHAT_ID=$(env_value TELEGRAM_CHAT_ID)
        curl -fsS "https://api.telegram.org/bot${TELEGRAM_BOT_TOKEN}/sendMessage" \
            --data-urlencode "chat_id=${TELEGRAM_CHAT_ID}" \
            --data-urlencode "text=monitoring: test alert from $(hostname) at $(date '+%Y-%m-%d %H:%M')" >/dev/null \
            && echo "sent -- check Telegram" || { echo "error: Telegram rejected the token / chat id" >&2; exit 1; }
        ;;
    *)
        echo "usage: $0 up|down|status|fit|test-alert|render" >&2
        exit 2
        ;;
esac
